export type Dictionary = typeof en;
export type MessageKey = DeepMessageKey<Dictionary>;

type DeepMessageKey<T> = {
  [K in keyof T & string]: T[K] extends string ? K : `${K}.${DeepMessageKey<T[K]>}`;
}[keyof T & string];

export function flattenMessages(dict: Dictionary): Record<string, string> {
  const out: Record<string, string> = {};
  const walk = (node: Record<string, unknown>, prefix: string): void => {
    for (const [key, value] of Object.entries(node)) {
      const fullKey = prefix ? `${prefix}.${key}` : key;
      if (typeof value === 'string') {
        out[fullKey] = value;
      } else if (value && typeof value === 'object') {
        walk(value as Record<string, unknown>, fullKey);
      }
    }
  };
  walk(dict as unknown as Record<string, unknown>, '');
  return out;
}
